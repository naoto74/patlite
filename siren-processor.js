class SirenProcessor extends AudioWorkletProcessor {

    constructor() {

        super();


        // -------------------------------------------------
        // 波形用
        // -------------------------------------------------

        this.phase = 0;


        // -------------------------------------------------
        // 基本周波数
        // -------------------------------------------------

        // 現在実際に鳴っている周波数
        this.f0 = 170;


        // -------------------------------------------------
        // モード
        // -------------------------------------------------

        this.mode = "idle";


        // -------------------------------------------------
        // モード開始時の周波数
        //
        // 「現在の周波数から上げる/下げる」を
        // 実現するために使用
        // -------------------------------------------------

        this.startFrequency = 170;


        // -------------------------------------------------
        // 自動モード用
        // -------------------------------------------------

        // 現在のセグメントが開始してからの時間
        // 単位: 秒
        this.segmentTime = 0;


        // 現在の自動モードの状態
        //
        // sec4:
        //     "up" -> "down" -> "up" ...
        //
        // sec8:
        //     "up" -> "down" -> "up" ...
        //
        this.autoDirection = "up";


        // -------------------------------------------------
        // メインスレッドからのメッセージ
        // -------------------------------------------------

        this.port.onmessage = event => {

            const data = event.data;

            if (!data) {
                return;
            }


            if (data.type === "mode") {

                this.setMode(data.mode);
            }
        };
    }


    // =====================================================
    // モード変更
    // =====================================================

    setMode(mode) {

        // ---------------------------------------------
        // 現在の周波数を新しいモードの開始周波数にする
        //
        // これによって
        //
        // 上げボタンを押した瞬間の周波数
        // ↓
        // 850Hzへ向かう
        //
        // という動作になる
        // ---------------------------------------------

        this.startFrequency = this.f0;


        // ---------------------------------------------
        // モード
        // ---------------------------------------------

        this.mode = mode;


        // ---------------------------------------------
        // 自動モードの時間をリセット
        // ---------------------------------------------

        this.segmentTime = 0;


        // ---------------------------------------------
        // 自動モードは必ず上昇から開始
        // ---------------------------------------------

        if (mode === "sec4" || mode === "sec8") {

            this.autoDirection = "up";
        }
    }


    // =====================================================
    // 指数関数による周波数計算
    // =====================================================

    /**
     * @param {number} start
     * @param {number} end
     * @param {number} k
     * @param {number} t
     * @returns {number}
     */
    exponentialFrequency(start, end, k, t) {

        return end
            + (start - end) * Math.exp(-k * t);
    }


    // =====================================================
    // 周波数計算
    // =====================================================

    calculateFrequency() {

        const t = this.segmentTime;


        // -------------------------------------------------
        // 手動 上げ
        // -------------------------------------------------

        if (this.mode === "up") {

            return this.exponentialFrequency(
                this.startFrequency,
                850,
                2.5,
                t
            );
        }


        // -------------------------------------------------
        // 手動 下げ
        // -------------------------------------------------

        if (this.mode === "down") {

            return this.exponentialFrequency(
                this.startFrequency,
                170,
                0.24,
                t
            );
        }


        // -------------------------------------------------
        // 電源 OFF
        // -------------------------------------------------

        if (this.mode === "off") {

            return this.exponentialFrequency(
                this.startFrequency,
                100,
                0.24,
                t
            );
        }


        // -------------------------------------------------
        // 自動4秒
        //
        // 上昇 2秒
        // ↓
        // 下降 2秒
        // ↓
        // 上昇 2秒
        // ...
        // -------------------------------------------------

        if (this.mode === "sec4") {

            if (this.autoDirection === "up") {

                return this.exponentialFrequency(
                    this.startFrequency,
                    850,
                    5,
                    t
                );

            } else {

                return this.exponentialFrequency(
                    this.startFrequency,
                    170,
                    0.47,
                    t
                );
            }
        }


        // -------------------------------------------------
        // 自動8秒
        //
        // 上昇 4.5秒
        // ↓
        // 下降 3.5秒
        // ↓
        // 上昇 4.5秒
        // ...
        // -------------------------------------------------

        if (this.mode === "sec8") {

            if (this.autoDirection === "up") {

                return this.exponentialFrequency(
                    this.startFrequency,
                    850,
                    2.5,
                    t
                );

            } else {

                return this.exponentialFrequency(
                    this.startFrequency,
                    170,
                    0.24,
                    t
                );
            }
        }


        // -------------------------------------------------
        // idle
        // -------------------------------------------------

        return this.f0;
    }


    // =====================================================
    // 自動モードの切り替え
    // =====================================================

    updateAutoMode() {

        // -------------------------------------------------
        // 4秒モード
        // -------------------------------------------------

        if (this.mode === "sec4") {

            const duration = 2;


            if (this.segmentTime >= duration) {

                // 現在の周波数を次のセグメントの
                // 開始周波数にする
                this.startFrequency = this.f0;


                // 時間をリセット
                this.segmentTime = 0;


                // 上下反転
                if (this.autoDirection === "up") {

                    this.autoDirection = "down";

                } else {

                    this.autoDirection = "up";
                }
            }

            return;
        }


        // -------------------------------------------------
        // 8秒モード
        // -------------------------------------------------

        if (this.mode === "sec8") {

            const duration =
                this.autoDirection === "up"
                    ? 4.5
                    : 3.5;


            if (this.segmentTime >= duration) {

                // 現在の周波数を次のセグメントの
                // 開始周波数にする
                this.startFrequency = this.f0;


                // 時間をリセット
                this.segmentTime = 0;


                // 上下反転
                if (this.autoDirection === "up") {

                    this.autoDirection = "down";

                } else {

                    this.autoDirection = "up";
                }
            }
        }
    }


    // =====================================================
    // 倍音
    // =====================================================

    getHarmonics(f0) {

        return {

            h2:
                f0 < 500
                    ? 0.1
                    : Math.max(
                        Math.min(
                            20 / (f0 - 450),
                            1.5
                        ),

                        2 / 3 *
                        Math.exp(
                            -1 / 50 *
                            (f0 - 525) ** 2
                        ),

                        2 / 5 *
                        Math.exp(
                            -1 / 100 *
                            (f0 - 570) ** 2
                        ),

                        2 / 5 *
                        Math.exp(
                            -1 / 400 *
                            (f0 - 620) ** 2
                        ),

                        2 / 5 *
                        Math.exp(
                            -1 / 400 *
                            (f0 - 680) ** 2
                        )
                    ),


            h3:
                f0 < 480
                    ? 0.1
                    : Math.max(
                        Math.min(
                            5 / (f0 - 410),
                            1.5
                        ),

                        1 / 5 *
                        Math.exp(
                            -1 / 400 *
                            (f0 - 645) ** 2
                        ),

                        1 / 2 *
                        Math.exp(
                            -1 / 300 *
                            (f0 - 765) ** 2
                        )
                    ),


            h4:
                f0 < 450
                    ? 0.1
                    : Math.max(
                        Math.min(
                            5 / (f0 - 400),
                            1.5
                        ),

                        1 / 10 *
                        Math.exp(
                            -1 / 700 *
                            (f0 - 640) ** 2
                        )
                    ),


            h5:
                f0 < 400
                    ? 0.1
                    : Math.max(
                        Math.min(
                            5 / (f0 - 350),
                            1.5
                        ),

                        1 / 8 *
                        Math.exp(
                            -1 / 700 *
                            (f0 - 480) ** 2
                        )
                    )
        };
    }


    // =====================================================
    // Audio処理
    // =====================================================

    process(inputs, outputs) {

        const output = outputs[0];

        const channel = output[0];

        if (!channel) {
            return true;
        }


        // AudioWorkletの1サンプルあたりの時間
        const deltaTime = 1 / sampleRate;


        for (
            let i = 0;
            i < channel.length;
            i++
        ) {


            // ---------------------------------------------
            // 自動モードの時間切り替え
            //
            // ここをサンプル単位で処理するので、
            // requestAnimationFrame() は不要
            // ---------------------------------------------

            this.updateAutoMode();


            // ---------------------------------------------
            // 周波数計算
            // ---------------------------------------------

            const targetFrequency =
                this.calculateFrequency();


            // ---------------------------------------------
            // 周波数を滑らかに追従
            // ---------------------------------------------
            //
            // 元プログラムの
            //
            // this.f0 +=
            //     (this.targetF0 - this.f0) * 0.001;
            //
            // と同じ考え方。
            //
            // ただし今回は targetF0 を使わず、
            // calculateFrequency() の結果を直接使用。
            // ---------------------------------------------

            this.f0 +=
                (
                    targetFrequency - this.f0
                ) * 0.001;


            const f0 = this.f0;


            // ---------------------------------------------
            // 倍音振幅
            // ---------------------------------------------

            const {
                h2,
                h3,
                h4,
                h5
            } = this.getHarmonics(f0);


            // ---------------------------------------------
            // 現在の位相
            // ---------------------------------------------

            const phase = this.phase;


            // ---------------------------------------------
            // 加算合成
            // ---------------------------------------------

            let sample =
                Math.sin(phase)
                + h2 * Math.sin(phase * 2)
                + h3 * Math.sin(phase * 3)
                + h4 * Math.sin(phase * 4)
                + h5 * Math.sin(phase * 5);


            // ---------------------------------------------
            // 位相を進める
            // ---------------------------------------------

            this.phase +=
                2 *
                Math.PI *
                f0 /
                sampleRate;


            // ---------------------------------------------
            // 0～2πに収める
            // ---------------------------------------------

            if (this.phase >= 2 * Math.PI) {

                this.phase -= 2 * Math.PI;
            }


            // ---------------------------------------------
            // 周波数による音量変化
            // ---------------------------------------------

            const f0vol =
                1 /
                (
                    1 +
                    Math.exp(
                        -1 / 50 *
                        (f0 - 500)
                    )
                );


            // ---------------------------------------------
            // 出力
            // ---------------------------------------------

            channel[i] =
                sample *
                f0vol;


            // ---------------------------------------------
            // 時間を進める
            // ---------------------------------------------

            this.segmentTime += deltaTime;
        }


        return true;
    }
}


registerProcessor(
    "siren-processor",
    SirenProcessor
);